static inline bool hub_hid_motion_bounded(int64_t x, int64_t y, int64_t wheel) {
    /* At most 32 split reports per event, so motion cannot bury button-up. */
    return x >= -32768 * 32 && x <= 32767 * 32
        && y >= -32768 * 32 && y <= 32767 * 32
        && wheel >= -128 * 32 && wheel <= 127 * 32;
}

